#!/usr/bin/env python3
"""Build NUMBERS_LEDGER.md and numbers_flat.json from the authoritative JSONs.

The ledger records WHERE every number lives. It does not interpret anything.
Re-run after any analysis change:  python3 build_ledger.py
"""
