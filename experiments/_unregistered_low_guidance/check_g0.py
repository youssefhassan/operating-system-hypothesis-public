"""
Validity check for the sub-CFG sweep.

Hard requirement
----------------
With CFG forced on, g = 0 collapses to the negative/unconditional branch — the
prompt is arithmetically cancelled. So at a given seed, **every prompt's g=0 image
must be byte-identical to every other prompt's g=0 image**. If they differ, the
patch in sweep_low_g.py did not take effect (diffusers fell back to the CFG-off
branch and quietly rendered the conditional image), and every number downstream is
meaningless. That is the pass/fail condition, and it exits non-zero.

Why `uncond_s{seed}.png` is reported but NOT asserted equal
-----------------------------------------------------------
It is a different anchor, and on SDXL it is genuinely a different image:

- SDXL's `model_index.json` sets `force_zeros_for_empty_prompt: true`, so when no
  negative prompt is passed the negative embedding is a **zero vector**. The g=0
  image is therefore the zero-embedding render.
- `uncond_s{seed}.png` is generated by passing `prompt=""`, which is the encoding
  of the empty string — not zeros. Different conditioning, different image.

- SD 3.5 takes the other path: Exp 03's `_build_sd3_embed` passes an explicit
  `negative_prompt=""`, so its negative branch *is* encode("") and its g=0 image
  should match `uncond`.

Both anchors are worth having (zero-embedding vs empty-string prior), so this
script prints the relationship per model instead of demanding one answer.
"""

from __future__ import annotations

import hashlib
import re
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
G0_RE = re.compile(r"^(?P<pid>p\d+_[a-z0-9]+)_g0_s(?P<s>\d+)\.png$")
UNCOND_RE = re.compile(r"^uncond_s(?P<s>\d+)\.png$")


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()[:16]


def check(model_dir: Path) -> bool:
    g0: dict[str, dict[str, str]] = defaultdict(dict)
    uncond: dict[str, str] = {}
    for png in sorted(model_dir.glob("*.png")):
        if m := G0_RE.match(png.name):
            g0[m.group("s")][png.name] = _sha(png)
        elif m := UNCOND_RE.match(png.name):
            uncond[m.group("s")] = _sha(png)

    if not g0:
        print(f"[check] {model_dir.name}: no g=0 images found — nothing to check")
        return True

    ok = True
    for seed, files in sorted(g0.items()):
        digests = set(files.values())
        if len(digests) == 1:
            d = digests.pop()
            note = ""
            if seed in uncond:
                note = ("  (== empty-string uncond)" if uncond[seed] == d
                        else "  (!= empty-string uncond, as expected on SDXL)")
            print(f"[check] {model_dir.name} seed {seed}: PASS — "
                  f"{len(files)} prompts all render {d}{note}")
        else:
            ok = False
            print(f"[check] {model_dir.name} seed {seed}: FAIL — {len(digests)} distinct "
                  f"images where there must be 1:")
            for name, d in sorted(files.items()):
                print(f"          {d}  {name}")
    return ok


if __name__ == "__main__":
    dirs = [p for p in sorted((HERE / "results-local").glob("*")) if p.is_dir()]
    if not dirs:
        raise SystemExit("no results-local/<model> directories yet — run the sweep first")
    if not all(check(d) for d in dirs):
        print("\n[check] g=0 images are not identical across prompts: the forced-CFG "
              "patch did not take. Do not analyze this run.", file=sys.stderr)
        raise SystemExit(1)
    print("\n[check] all good — CFG really was on below g=1.")
